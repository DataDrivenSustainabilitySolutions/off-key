-- A run's lifecycle events and last status outlive its service row, which stop
-- and retention purge delete, so a failed or stopped run can be reconstructed.
ALTER TABLE monitoring_pipeline_runs
    ADD COLUMN IF NOT EXISTS final_status jsonb;
CREATE TABLE IF NOT EXISTS monitoring_pipeline_run_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL REFERENCES monitoring_pipeline_runs(id) ON DELETE CASCADE,
    occurred_at timestamptz NOT NULL DEFAULT now(),
    source text NOT NULL,
    kind text NOT NULL,
    stage text,
    detail jsonb NOT NULL,
    CONSTRAINT ck_pipeline_run_event_source CHECK (source IN ('radar', 'tactic'))
);
CREATE INDEX IF NOT EXISTS ix_monitoring_pipeline_run_events_run_time
    ON monitoring_pipeline_run_events (run_id, occurred_at, id);
