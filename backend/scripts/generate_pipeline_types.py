"""Generate browser contracts from the canonical Pydantic pipeline schemas."""

import argparse
import inspect
import json
from pathlib import Path

from off_key_core.schemas import pipelines
from pydantic import BaseModel


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    alternatives = schema.get("anyOf", schema.get("oneOf"))
    if alternatives:
        return " | ".join(typescript(item) for item in alternatives)
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean"}:
        return kind
    if kind == "array":
        return array_type(schema)
    if kind == "object":
        return object_type(schema)
    return "unknown"


def array_type(schema: dict) -> str:
    if "prefixItems" in schema:
        return "[" + ", ".join(typescript(item) for item in schema["prefixItems"]) + "]"
    return f"Array<{typescript(schema.get('items', {}))}>"


def object_type(schema: dict) -> str:
    properties = schema.get("properties")
    if not properties:
        additional = schema.get("additionalProperties", {})
        value = typescript(additional) if isinstance(additional, dict) else "unknown"
        return f"Record<string, {value}>"
    required = schema.get("required", [])
    fields = [
        f"  {name}{'' if name in required else '?'}: {typescript(value)};"
        for name, value in properties.items()
    ]
    return "{\n" + "\n".join(fields) + "\n}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    definitions = {}
    for name, model in inspect.getmembers(pipelines, inspect.isclass):
        if model.__module__ != pipelines.__name__ or not issubclass(model, BaseModel):
            continue
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[name] = schema
    text = (
        "// Generated by backend/scripts/generate_pipeline_types.py; do not edit.\n\n"
    )
    text += (
        "\n\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )
    # Authoring limits come from the definition schema, so --check catches drift.
    limits = pipelines.PipelineDefinition.model_json_schema()["properties"]
    text += (
        "\nexport const PIPELINE_LIMITS = { "
        f"nodes: {limits['nodes']['maxItems']}, "
        f"edges: {limits['edges']['maxItems']}, "
        f"slots: {limits['input_slots']['maxItems']} }} as const;\n"
    )
    target = (
        Path(__file__).resolve().parents[2]
        / "frontend/src/types/pipelines.generated.ts"
    )
    if options.check:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            raise SystemExit("Pipeline browser contracts are stale; regenerate them")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
