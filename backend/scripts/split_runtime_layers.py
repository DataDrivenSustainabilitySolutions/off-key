"""Separate installed workspace files from dependencies without changing the venv.

Both output trees are copied back to the original venv path in the final image.
Only local workspace distributions move; third-party packages stay in the stable
dependency layer. RECORD entries and generated bytecode cover their runtime files.
"""

import argparse
import importlib.metadata
import json
import os
import shutil
from pathlib import Path
from urllib.parse import unquote, urlparse


def workspace_distributions(environment, project):
    for site in environment.glob("lib/python*/site-packages"):
        for distribution in importlib.metadata.distributions(path=[str(site)]):
            origin = distribution.read_text("direct_url.json")
            if origin is None:
                continue
            source = urlparse(json.loads(origin)["url"])
            if source.scheme != "file" or not Path(unquote(source.path)).is_relative_to(
                project
            ):
                continue
            yield distribution


def workspace_files(environment, project):
    files = set()
    packages = []
    for distribution in workspace_distributions(environment, project):
        if distribution.files is None:
            raise ValueError(f"Missing installed-file record for {distribution.name}")
        packages.append(distribution.name)
        for entry in distribution.files:
            path = Path(os.path.normpath(distribution.locate_file(entry)))
            if not path.is_relative_to(environment):
                raise ValueError(f"Workspace file is outside its venv: {path}")
            if path.is_file() or path.is_symlink():
                files.add(path)
                if path.suffix == ".py":
                    files.update(
                        (path.parent / "__pycache__").glob(f"{path.stem}.*.pyc")
                    )
    if not packages:
        raise ValueError("No installed workspace distributions found")
    return files, sorted(packages)


def split(environment, project, application):
    files, packages = workspace_files(environment, project)
    application.mkdir(parents=True, exist_ok=False)
    shutil.copystat(environment, application)
    parents = set()
    for source in sorted(files):
        target = application / source.relative_to(environment)
        target.parent.mkdir(parents=True, exist_ok=True)
        for parent in target.parents:
            if parent == application:
                break
            shutil.copystat(environment / parent.relative_to(application), parent)
        source.rename(target)
        parents.update(
            parent
            for parent in source.parents
            if parent != environment and parent.is_relative_to(environment)
        )
    # Empty workspace directories must not invalidate the dependency layer either.
    for parent in sorted(parents, key=lambda path: len(path.parts), reverse=True):
        if parent.exists() and not any(parent.iterdir()):
            parent.rmdir()
    print(f"Separated {len(files)} installed files for {', '.join(packages)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("environment", type=Path)
    parser.add_argument("project", type=Path)
    parser.add_argument("application", type=Path)
    args = parser.parse_args()
    split(args.environment, args.project, args.application)
