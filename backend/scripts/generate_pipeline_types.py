"""Generate browser contracts from the canonical Pydantic pipeline and Dojo schemas."""

import argparse
import inspect
import json
import re
from pathlib import Path

from off_key_core.schemas import dojo, pipelines
from pydantic import BaseModel


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    alternatives = schema.get("anyOf", schema.get("oneOf"))
    if alternatives:
        return " | ".join(typescript(item) for item in alternatives)
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean"}:
        return kind
    if kind == "array":
        return array_type(schema)
    if kind == "object":
        return object_type(schema)
    return "unknown"


def array_type(schema: dict) -> str:
    if "prefixItems" in schema:
        return "[" + ", ".join(typescript(item) for item in schema["prefixItems"]) + "]"
    return f"Array<{typescript(schema.get('items', {}))}>"


def object_type(schema: dict) -> str:
    properties = schema.get("properties")
    if not properties:
        additional = schema.get("additionalProperties", {})
        value = typescript(additional) if isinstance(additional, dict) else "unknown"
        return f"Record<string, {value}>"
    required = schema.get("required", [])
    fields = [
        f"  {name}{'' if name in required else '?'}: {typescript(value)};"
        for name, value in properties.items()
    ]
    return "{\n" + "\n".join(fields) + "\n}"


def contracts(module) -> dict:
    """Every Pydantic model defined in ``module`` and the models it refers to."""
    definitions = {}
    for name, model in inspect.getmembers(module, inspect.isclass):
        if model.__module__ != module.__name__ or not issubclass(model, BaseModel):
            continue
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[name] = schema
    return definitions


def declarations(definitions: dict) -> str:
    return (
        "\n\n".join(
            f"export type {name} = {typescript(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )


def pipeline_contracts(definitions: dict) -> str:
    text = (
        "// Generated by backend/scripts/generate_pipeline_types.py; do not edit.\n\n"
    )
    text += declarations(definitions)
    # Authoring limits come from the definition schema, so --check catches drift.
    limits = pipelines.PipelineDefinition.model_json_schema()["properties"]
    text += (
        "\nexport const PIPELINE_LIMITS = { "
        f"nodes: {limits['nodes']['maxItems']}, "
        f"edges: {limits['edges']['maxItems']}, "
        f"slots: {limits['input_slots']['maxItems']}, "
        f"detectors: {pipelines.MAX_DETECTORS} }} as const;\n"
    )
    return text


def dojo_contracts(shared: dict) -> str:
    """Dojo contracts; models the pipeline contracts already declare are imported."""
    definitions = contracts(dojo)
    own = {name: schema for name, schema in definitions.items() if name not in shared}
    body = declarations(own)
    imported = sorted(
        name
        for name in definitions.keys() & shared.keys()
        if re.search(rf"\b{name}\b", body)
    )
    text = (
        "// Generated by backend/scripts/generate_pipeline_types.py; do not edit.\n\n"
    )
    if imported:
        text += (
            f'import type {{ {", ".join(imported)} }} from "./pipelines.generated";\n\n'
        )
    text += body
    text += (
        "\nexport const DOJO_LIMITS = { "
        f"uploadBytes: {dojo.MAX_UPLOAD_BYTES}, "
        f"series: {dojo.MAX_DATASET_SERIES}, "
        f"points: {dojo.MAX_DATASET_POINTS}, "
        f"pointsPage: {dojo.MAX_POINTS_PAGE}, "
        f"resultsPage: {dojo.MAX_RESULTS_PAGE}, "
        f"labels: {dojo.MAX_DATASET_LABELS}, "
        f"comparedRuns: {dojo.MAX_COMPARED_RUNS} }} as const;\n"
    )
    return text


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    shared = contracts(pipelines)
    types = Path(__file__).resolve().parents[2] / "frontend/src/types"
    files = {
        types / "pipelines.generated.ts": pipeline_contracts(shared),
        types / "dojo.generated.ts": dojo_contracts(shared),
    }
    for target, text in files.items():
        if options.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                raise SystemExit(f"{target.name} is stale; regenerate it")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
